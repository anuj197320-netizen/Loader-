async def spam_worker_with_counter(bot, chat_id: int, target_text: str, slot: int, counter_dict: Dict[int, int]):
    texts = SPAM_TEXTS_MAP.get(slot, SPAM1_TEXTS)
    idx = 0
    while True:
        try:
            template = texts[idx % len(texts)]
            msg = template.replace("{target}", target_text)
            await bot.send_message(chat_id=chat_id, text=msg)
            counter_dict[chat_id] = counter_dict.get(chat_id, 0) + 1
            idx += 1
            await asyncio.sleep(GLOBAL_DELAY)
        except asyncio.CancelledError:
            break
        except RetryAfter as e:
            await asyncio.sleep(e.retry_after)
        except Exception:
            await asyncio.sleep(0.05)

