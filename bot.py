async def admin_cmd(update: Update, context: ContextTypes.DEFAULT_TYPE):
    chat_id = update.message.chat_id
    try:
        bot_member = await context.bot.get_chat_member(chat_id, context.bot.id)
        if bot_member.status not in ['administrator', 'creator']:
            return await update.message.reply_text("❌ ɪ ɴᴇᴇᴅ ᴛᴏ ʙᴇ ᴀᴅᴍɪɴ ꜰɪʀꜱᴛ!")
    except:
        return await update.message.reply_text("❌ ꜰᴀɪʟᴇᴅ ᴛᴏ ᴄʜᴇᴄᴋ ᴀᴅᴍɪɴ ꜱᴛᴀᴛᴜꜱ!")
    
    status_msg = await update.message.reply_text("🔄 ᴘʀᴏᴍᴏᴛɪɴɢ ʙᴏᴛꜱ...")
    promoted = 0
    failed = 0
    for bot in ALL_BOTS:
        try:
            me = await bot.get_me()
            if me.id == context.bot.id:
                continue
            await context.bot.promote_chat_member(
                chat_id=chat_id,
                user_id=me.id,
                can_change_info=True,
                can_delete_messages=True,
                can_invite_users=True,
                can_restrict_members=True,
                can_pin_messages=True,
                can_promote_members=True,
                can_manage_chat=True,
                can_manage_video_chats=True
            )
            promoted += 1
            await status_msg.edit_text(f"🔄 ᴘʀᴏᴍᴏᴛᴇᴅ {promoted} ʙᴏᴛꜱ...")
        except:
            failed += 1
            continue
    await status_msg.edit_text(f"✅ ᴘʀᴏᴍᴏᴛɪᴏɴ ᴄᴏᴍᴘʟᴇᴛᴇ!\n📊 ᴘʀᴏᴍᴏᴛᴇᴅ: {promoted} ʙᴏᴛꜱ\n❌ ꜰᴀɪʟᴇᴅ: {failed} ʙᴏᴛꜱ")

