@only_sudo
async def delay_cmd(update: Update, context: ContextTypes.DEFAULT_TYPE):
    global GLOBAL_DELAY
    if not context.args:
        await update.message.reply_text(f"ᴄᴜʀʀᴇɴᴛ ᴅᴇʟᴀʏ: {GLOBAL_DELAY}s\nᴜꜱᴀɢᴇ: !delay <seconds>")
        return
    try:
        new_delay = float(context.args[0])
        if new_delay < 0.0:
            new_delay = 0.0
        if new_delay > 5.0:
            new_delay = 5.0
        GLOBAL_DELAY = new_delay
        await update.message.reply_text(f"✅ ᴅᴇʟᴀʏ ꜱᴇᴛ ᴛᴏ {GLOBAL_DELAY}s")
    except:
        await update.message.reply_text("❌ ɪɴᴠᴀʟɪᴅ ɴᴜᴍʙᴇʀ!")

